//! scene 页面场景模块
//!
//! # 本文件职责
//! 本文件是启动器「页面层」的模块声明集合（module root），本身不含任何代码逻辑，
//! 只负责把 `src/app/pages/` 目录下各个页面子模块挂载到模块树中，并统一控制它们的可见性。
//! 上层（`crate::app` 内的 `shell.rs` / `input.rs` 等调度代码）通过这些子模块，
//! 把首页 / 下载 / 收藏 / 设置等不同场景的绘制逻辑分派到对应的实现文件里，
//! 从而让「导航状态 → 具体页面渲染」的解耦得以成立。
//!
//! # 主要定义
//! - 本文件不定义类型、常量或函数，仅包含 7 条 `mod` 声明（见下方逐条说明）。
//!
//! # 在启动器中的角色
//! 本模块由 `src/app/mod.rs` 中的 `mod pages;` 挂载，因此父模块是 `crate::app`；
//! 页面内部的 `impl LauncherApp` 方法通常声明为 `pub(in crate::app)`，
//! 与本模块 `pub(super)` 的可见性范围相互配合，
//! 保证页面实现细节不会泄漏到 `crate::app` 之外。
//!
//! # 可见性说明
//! 全部子模块均使用 `pub(super)`：仅父模块 `crate::app` 内部可访问，对外隔离子模块细节。
//! 若后续需要在别处直接引用某个页面模块，
//! 需要把该模块的可见性放宽为 `pub(in crate::app)`；当前设计刻意保持收敛。

/// 创造页面（皮肤编辑器 / 模组工程生成器）
///
/// 对应文件 `src/app/pages/create.rs`。
/// 提供「创造」标签页的绘制与交互，主要包括 64×64 皮肤的像素绘制、导入导出、
/// 撤销重做与 3D 角色预览，以及按表单生成可编译的 Java + Gradle 模组工程脚手架。
pub(super) mod create;
/// 下拉菜单与各类对话框 / 弹窗
///
/// 对应文件 `src/app/pages/dialogs.rs`。
/// 集中实现顶部下拉菜单（版本选择、玩家资料）以及若干浮动弹层
/// （模态对话框、Toast、官方版本浏览器、安装 / 导入进度等）的绘制与事件响应。
pub(super) mod dialogs;
/// 下载页面
///
/// 对应文件 `src/app/pages/download.rs`。
/// 承载「下载」标签页：原版游戏版本列表与详情，以及基于 Modrinth 的社区资源搜索 / 下载界面，
/// 并处理顶部分类切换与页面转场动画。
pub(super) mod download;
/// 收藏页面
///
/// 对应文件 `src/app/pages/favorites.rs`。
/// 以卡片网格展示内置与用户自定义的收藏网站，支持打开、删除与虚拟滚动，
/// 并提供「添加收藏」弹窗（名称 / 网址 / 图标，可就地抓取 favicon）。
pub(super) mod favorites;
/// 首页主页
///
/// 对应文件 `src/app/pages/home.rs`。
/// 启动器启动后的默认场景，包含 hero 首屏、最近游玩卡片、启动坞、
/// 启动设置卡、加载器安装对话框与最新动态卡片。
pub(super) mod home;
/// 设置中心页面
///
/// 对应文件 `src/app/pages/settings.rs`。
/// 按设置区块（section）绘制左侧分类导航与右侧具体设置项，
/// 并在区块切换时做离场 / 入场转场；读写都发生在 `self.settings` 上并持久化到本机配置。
pub(super) mod settings;
/// 版本页面
///
/// 对应文件 `src/app/pages/versions.rs`。
/// 绘制版本主页面（左侧版本列表 + 右侧详情）、游戏文件夹选择菜单、
/// 模组 / 存档 / 光影等内容浏览对话框、Java 运行时选择浮层与整合包导出选项。
pub(super) mod versions;
